/** Small adapter so PDF->PNG reuses the JPG runner with a format override. */
function runPdfToImagesFormat(format: 'png' | 'jpg') {
  return async (files: File[], opts: OptionValues, ctx: Parameters<typeof runPdfToImages>[2]) => {
    return runPdfToImages(files, { ...opts, format }, ctx);
  };
}

export function getTool(id: string): ToolDef | undefined {
  return TOOLS.find((t) => t.id === id);
}

export function toolsByGroup(group: ToolGroup): ToolDef[] {
  return TOOLS.filter((t) => t.group === group);
}
